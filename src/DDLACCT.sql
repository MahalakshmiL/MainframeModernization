------------------------------------------------------------------
-- DDLACCT.SQL
-- DB2 TARGET TABLES FOR THE DEPOSIT / ACCOUNT SERVICING MODULE.
--
-- NOTE ON ACCT_INT_RATE / ACCT_FEE_CODE:
-- IN THE COBOL COPYBOOK (ACCTREC.CPY) THESE TWO FIELDS SHARE THE
-- SAME PHYSICAL STORAGE VIA REDEFINES - ONLY ONE IS MEANINGFUL AT
-- A TIME, DEPENDING ON ACCT_TYPE. DB2 HAS NO EQUIVALENT OF
-- REDEFINES, SO THE UNLOAD SPLITS THEM INTO TWO SEPARATE NULLABLE
-- COLUMNS. ANY FIELD-LEVEL LINEAGE FOR EITHER COLUMN MUST NOTE
-- THAT THEY ORIGINATE FROM THE SAME COBOL BYTES.
------------------------------------------------------------------
CREATE TABLE ACCOUNT_MASTER (
    ACCT_ID              CHAR(10)      NOT NULL,
    ACCT_CUSTOMER_ID      CHAR(10)      NOT NULL,
    ACCT_TYPE            CHAR(1)       NOT NULL,
    ACCT_STATUS          CHAR(1)       NOT NULL,
    ACCT_BALANCE         DECIMAL(11,2) NOT NULL,
    ACCT_OPEN_DATE        DATE          NOT NULL,
    ACCT_LAST_TRAN_DATE    DATE          NOT NULL,
    ACCT_INT_RATE         DECIMAL(4,3)  ,
    ACCT_FEE_CODE         CHAR(4)       ,
    ACCT_DORMANT_DAYS      INTEGER       NOT NULL,
    PRIMARY KEY (ACCT_ID)
);

CREATE TABLE TRANSACTION_LOG (
    TRAN_ID              CHAR(12)      NOT NULL,
    TRAN_ACCT_ID          CHAR(10)      NOT NULL,
    TRAN_TYPE            CHAR(2)       NOT NULL,
    TRAN_AMOUNT           DECIMAL(11,2) NOT NULL,
    TRAN_DATE             DATE          NOT NULL,
    TRAN_BALANCE_AFTER      DECIMAL(11,2) NOT NULL,
    TRAN_DESC             VARCHAR(30)   ,
    PRIMARY KEY (TRAN_ID),
    FOREIGN KEY (TRAN_ACCT_ID) REFERENCES ACCOUNT_MASTER (ACCT_ID)
);

CREATE INDEX IX_TRANLOG_ACCT ON TRANSACTION_LOG (TRAN_ACCT_ID, TRAN_DATE);
